const roundMoney = (value) => Math.round(Number(value) * 100) / 100;

/**
 * VARIANT items = finish columns only.
 * PG / SB live on attributes (colour / price-group mapping), not as columns.
 */
const buildVariantItems = (sizeFactor = 1) =>
  CATALOGUE_FINISHES.map((finish, index) => {
    const retailPrice =
      finish.basePrice == null ? null : roundMoney(finish.basePrice * sizeFactor);
    return {
      quantity: 1,
      sortOrder: index,
      attributes: {
        finishName: finish.finishName,
        priceGroup: finish.winnerPriceGroup,
        winnerPriceGroup: finish.winnerPriceGroup,
        edgingPriceGroup: finish.edgingPriceGroup,
        solidBackGroup: finish.solidBackGroup || '',
        retailPrice,
        status: 'Active',
      },
    };
  });

